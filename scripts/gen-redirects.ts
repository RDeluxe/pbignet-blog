/**
 * gen-redirects.ts — writes the 301 list the production nginx serves for Ghost's old URLs.
 *
 *   pnpm redirects            → rewrites redirects/redirects.map and redirects/missing-images.txt
 *   pnpm redirects --check    → exits 1 when those files are out of date (no write)
 *
 * redirects/redirects.map is a plain list of `/old /new;` lines, meant for the inside of an
 * nginx `map $uri $redirect_target { default ""; include …/redirects.map; }`. It holds:
 * - every published post of `src/content/writing` (no `draft`) that came from Ghost, i.e. has
 *   a `link`: `/<ghost-slug>/` → `/writing/<file-slug>/` (and the form without the slash);
 * - the fixed routes: `/sitemap.xml`, `/rss/`, `/feed/`;
 * - `redirects/manual.map`, copied as is: the lines nobody can derive (a post not migrated);
 * - Ghost's images (`redirects/ghost-images.txt`, harvested from the old blog) that exist in
 *   the new site under `public/writing/`, matched by file name, size variants included.
 * The Ghost images with no equivalent are listed in redirects/missing-images.txt instead.
 */

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { basename, extname, join, resolve } from 'node:path'
import process from 'node:process'
import { parse as parseYaml } from 'yaml'

const REPO = resolve(import.meta.dirname, '..')
const CONTENT_DIR = join(REPO, 'src/content/writing')
const WRITING_PUBLIC = join(REPO, 'public/writing')
const OUT_DIR = join(REPO, 'redirects')

/** same rule as vault-to-post.ts: how an image's file name is stored in public/writing/ */
function slugify(text: string): string {
  return text.normalize('NFD').replace(/\p{M}/gu, '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
}

function storedName(ghostPath: string): string {
  const base = basename(ghostPath)
  const ext = extname(base)
  return `${slugify(basename(base, ext))}${ext.toLowerCase()}`
}

interface Post { slug: string, ghostPath: string }

function publishedGhostPosts(): Post[] {
  const posts: Post[] = []
  for (const file of readdirSync(CONTENT_DIR).sort()) {
    if (!/\.(?:md|mdoc)$/.test(file))
      continue
    const match = readFileSync(join(CONTENT_DIR, file), 'utf8').match(/^---\r?\n([\s\S]*?)\r?\n---/)
    const meta = (match ? parseYaml(match[1]) : {}) as { draft?: boolean, link?: string }
    if (meta.draft || !meta.link)
      continue
    posts.push({ slug: file.replace(/\.(?:md|mdoc)$/, ''), ghostPath: new URL(meta.link).pathname })
  }
  return posts
}

/** file name → `/writing/<slug>/<file>` for every image the migration stored */
function migratedImages(): Map<string, string> {
  const images = new Map<string, string>()
  for (const dir of readdirSync(WRITING_PUBLIC, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort()) {
    for (const file of readdirSync(join(WRITING_PUBLIC, dir))) {
      if (!images.has(file))
        images.set(file, `/writing/${dir}/${file}`)
    }
  }
  return images
}

function lines(path: string): string[] {
  return existsSync(path) ? readFileSync(path, 'utf8').split('\n').map(l => l.trim()).filter(Boolean) : []
}

function build(): { map: string, missing: string } {
  const entries: string[] = []
  const add = (from: string, to: string) => entries.push(`${from} ${to};`)

  entries.push('# posts: Ghost serves /<slug>/, the new site /writing/<slug>/')
  for (const { slug, ghostPath } of publishedGhostPosts()) {
    const target = `/writing/${slug}/`
    add(ghostPath, target)
    add(ghostPath.replace(/\/$/, ''), target)
  }

  entries.push('', '# sitemap and feed')
  add('/sitemap.xml', '/sitemap-index.xml')
  add('/rss/', '/rss.xml')
  add('/rss', '/rss.xml')
  add('/feed/', '/rss.xml')
  add('/feed', '/rss.xml')

  const manual = lines(join(OUT_DIR, 'manual.map')).filter(l => !l.startsWith('#'))
  if (manual.length)
    entries.push('', '# redirects/manual.map', ...manual)

  const migrated = migratedImages()
  const found: string[] = []
  const missing: string[] = []
  for (const path of lines(join(OUT_DIR, 'ghost-images.txt'))) {
    const target = migrated.get(storedName(path))
    if (target)
      found.push(`${path} ${target};`)
    else missing.push(path)
  }
  entries.push('', '# Ghost images that exist in the new site', ...found)

  const missingFile = [
    '# Ghost images with no equivalent in the new site (generated by `pnpm redirects`).',
    '# No redirect: they were covers the migration dropped, or never migrated.',
    ...missing,
  ]
  const header = [
    '# Ghost → exhale 301 redirects. GENERATED by `pnpm redirects`: edit manual.map, not this file.',
    '# Meant for nginx: map $uri $redirect_target { default ""; include /path/to/redirects.map; }',
    '',
  ]
  return { map: `${[...header, ...entries].join('\n')}\n`, missing: `${missingFile.join('\n')}\n` }
}

const { map, missing } = build()
const targets = [[join(OUT_DIR, 'redirects.map'), map], [join(OUT_DIR, 'missing-images.txt'), missing]] as const

if (process.argv.includes('--check')) {
  const stale = targets.filter(([path, content]) => !existsSync(path) || readFileSync(path, 'utf8') !== content)
  if (stale.length) {
    console.error(`out of date: ${stale.map(([p]) => basename(p)).join(', ')} — run pnpm redirects`)
    process.exit(1)
  }
  console.log('redirects up to date')
}
else {
  for (const [path, content] of targets)
    writeFileSync(path, content)
  console.log(`redirects/redirects.map: ${map.split('\n').filter(l => l.endsWith(';')).length} redirects; missing-images.txt: ${missing.split('\n').filter(l => l.startsWith('/')).length} images without equivalent`)
}
